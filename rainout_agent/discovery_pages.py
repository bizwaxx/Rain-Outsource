"""Small static discovery pages served by the existing index function (no extra Vercel function).

Paths: ``/privacy``, ``/terms`` (draft HTML), ``/icon.png`` (generated by ``scripts/make_icon.py``)
and ``/.well-known/mcp/server-card.json`` (built at request time from the live MCP tool list,
so it can't drift from ``tools/list``). Files live in ``static_pages/`` at the repo root.
Used by ``api/index.py`` on Vercel and by the local WSGI app.
"""
from __future__ import annotations

import json
from pathlib import Path
from urllib.parse import urlsplit

PAGES_DIR = Path(__file__).resolve().parents[1] / "static_pages"
BASE_URL = "https://rainout-agent-source.vercel.app"

PAGE_CACHE = "public, max-age=300, s-maxage=86400"
ICON_CACHE = "public, max-age=86400, s-maxage=604800"
SERVER_CARD_PATH = "/.well-known/mcp/server-card.json"

# path -> (file in static_pages/, content type, cache-control)
FILES: dict[str, tuple[str, str, str]] = {
    "/privacy": ("privacy.html", "text/html; charset=utf-8", PAGE_CACHE),
    "/terms": ("terms.html", "text/html; charset=utf-8", PAGE_CACHE),
    "/icon.png": ("icon.png", "image/png", ICON_CACHE),
}
ALIASES = {"/privacy.html": "/privacy", "/terms.html": "/terms", "/.well-known/mcp/server-card": SERVER_CARD_PATH}
PATHS = tuple(FILES) + (SERVER_CARD_PATH,) + tuple(ALIASES)


def server_card() -> dict:
    from rainout_agent.mcp_server import SERVER_NAME, SERVER_VERSION, SUPPORTED_VERSIONS, TOOLS

    return {
        "serverInfo": {"name": SERVER_NAME, "title": "Rain-Outsource", "version": SERVER_VERSION},
        "description": "Check any weather-dependent plan: will the game, race or event happen, and rain odds worldwide.",
        "transport": {"type": "streamable-http", "url": f"{BASE_URL}/mcp"},
        "protocolVersions": list(SUPPORTED_VERSIONS),
        "capabilities": {"tools": {"listChanged": False}},
        "authentication": {"required": False},
        "tools": TOOLS,
        "resources": [],
        "prompts": [],
        "links": {
            "repository": "https://github.com/bizwaxx/Rain-Outsource",
            "documentation": "https://bizwaxx.github.io/Rain-Outsource/",
            "icon": f"{BASE_URL}/icon.png",
            "privacy": f"{BASE_URL}/privacy",
            "terms": f"{BASE_URL}/terms",
        },
    }


def normalize(path: str) -> str:
    p = urlsplit(path or "/").path or "/"
    if p != "/" and p.endswith("/"):
        p = p.rstrip("/")
    return ALIASES.get(p, p)


def lookup(path: str) -> tuple[int, str, bytes, str] | None:
    """(status, content_type, body, cache_control) for a discovery path, else None."""
    p = normalize(path)
    if p == SERVER_CARD_PATH:
        return 200, "application/json", json.dumps(server_card(), indent=2).encode("utf-8"), PAGE_CACHE
    if p in FILES:
        name, ctype, cache = FILES[p]
        return 200, ctype, (PAGES_DIR / name).read_bytes(), cache
    return None
