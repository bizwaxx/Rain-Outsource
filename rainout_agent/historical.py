"""Historical rain climatology for supported fields.

Each field has a ``data/historical/<name>-historical.json`` document. Besides the
hand-entered ``historical_cancellations`` list, the document now carries a
``noaa_history`` block generated by ``scripts/fetch_noaa_history.py`` from real
NOAA GHCN-Daily precipitation observations at the nearest suitable station.

This module holds the pure climatology math (shared with the fetch script and
tests) and the runtime lookup used to calibrate play probability.
"""
from __future__ import annotations

import json
from datetime import date, datetime
from functools import lru_cache
from pathlib import Path
from typing import Any, Iterable

DATA_DIR = Path(__file__).resolve().parents[1] / "data"
HISTORICAL_DIR = DATA_DIR / "historical"

# Daily rain total (inches) at which games at this kind of field are usually
# rained out. Skinned dirt infields (baseball/softball) go unplayable sooner
# than grass or turf multipurpose fields. A field file can override this with
# "rain_to_cancel_threshold_in", and scale it with "drainage".
SPORT_THRESHOLDS_IN = {
    "softball": 0.5,
    "baseball": 0.5,
    "baseball/softball": 0.5,
    "baseball_softball": 0.5,
    "soccer": 0.75,
    "multipurpose fields": 0.75,
    "motocross": 1.0,
}
DEFAULT_THRESHOLD_IN = 0.5
DRAINAGE_FACTORS = {"poor": 0.75, "average": 1.0, "good": 1.5}

WET_DAY_IN = 0.01  # NWS probability of precipitation is for >= 0.01 inch.
REPORT_THRESHOLDS_IN = (0.1, 0.25, 0.5, 0.75, 1.0)

# Heavy-rain severity is blended with this floor so that history can only
# soften the raw rain chance, never ignore it: wet grounds, lightning rules and
# field-crew calls cancel games below the daily threshold too.
SEVERITY_FLOOR = 0.5


def threshold_key(value: float) -> str:
    return "p_ge_" + f"{value:.2f}".replace(".", "_")


def rain_to_cancel_threshold_in(field: dict[str, Any]) -> float:
    """Daily rain total that typically rains out games at this field."""
    explicit = field.get("rain_to_cancel_threshold_in")
    if isinstance(explicit, (int, float)) and explicit > 0:
        base = float(explicit)
    else:
        sport = str(field.get("sport") or "").strip().lower()
        base = SPORT_THRESHOLDS_IN.get(sport, DEFAULT_THRESHOLD_IN)
    factor = DRAINAGE_FACTORS.get(str(field.get("drainage") or "average").lower(), 1.0)
    return round(base * factor, 2)


def compute_climatology(
    daily: Iterable[tuple[date, float | None]],
    cancel_threshold_in: float,
    period_days: int | None = None,
) -> dict[str, Any]:
    """Summarise daily precipitation observations into monthly rain stats.

    ``daily`` is an iterable of ``(date, inches)``; ``None`` means missing.
    Returns overall coverage, annual figures, per-month frequencies and the
    list of days at or above the cancellation threshold.
    """
    months: dict[int, dict[str, Any]] = {
        m: {"days": 0, "total": 0.0, "wet": 0, "counts": {t: 0 for t in REPORT_THRESHOLDS_IN}, "cancel": 0}
        for m in range(1, 13)
    }
    years: set[int] = set()
    observed = 0
    heavy_days = []
    for day, prcp in daily:
        if prcp is None:
            continue
        observed += 1
        years.add(day.year)
        bucket = months[day.month]
        bucket["days"] += 1
        bucket["total"] += prcp
        if prcp >= WET_DAY_IN:
            bucket["wet"] += 1
        for t in REPORT_THRESHOLDS_IN:
            if prcp >= t:
                bucket["counts"][t] += 1
        if prcp >= cancel_threshold_in:
            bucket["cancel"] += 1
            heavy_days.append({"date": day.isoformat(), "prcp_in": round(prcp, 2)})

    monthly: dict[str, Any] = {}
    total_rain = total_wet = total_cancel = 0.0
    for m, b in months.items():
        days = b["days"]
        total_rain += b["total"]
        total_wet += b["wet"]
        total_cancel += b["cancel"]
        entry: dict[str, Any] = {"days_observed": days}
        if days:
            entry["mean_precip_in"] = round(b["total"] / days * _days_in_month(m), 2)
            entry["wet_day_frac"] = round(b["wet"] / days, 3)
            for t in REPORT_THRESHOLDS_IN:
                entry[threshold_key(t)] = round(b["counts"][t] / days, 3)
            entry["rainout_day_frac"] = round(b["cancel"] / days, 3)
            entry["cancel_given_wet"] = round(b["cancel"] / b["wet"], 3) if b["wet"] else 0.0
        monthly[f"{m:02d}"] = entry

    n_years = (observed / 365.25) if observed else 0
    result: dict[str, Any] = {
        "days_observed": observed,
        "coverage_percent": round(100 * observed / period_days, 1) if period_days else None,
        "rain_to_cancel_threshold_in": cancel_threshold_in,
        "annual": {
            "mean_precip_in": round(total_rain / n_years, 1) if n_years else None,
            "wet_days_per_year": round(total_wet / n_years, 1) if n_years else None,
            "rainout_days_per_year": round(total_cancel / n_years, 1) if n_years else None,
            "cancel_given_wet": round(total_cancel / total_wet, 3) if total_wet else None,
        },
        "monthly": monthly,
        "rainout_level_days": heavy_days,
    }
    return result


def _days_in_month(month: int) -> float:
    return {2: 28.25, 4: 30, 6: 30, 9: 30, 11: 30}.get(month, 31)


@lru_cache(maxsize=1)
def _profiles_by_field_id() -> dict[str, dict[str, Any]]:
    profiles: dict[str, dict[str, Any]] = {}
    if not HISTORICAL_DIR.exists():
        return profiles
    for path in sorted(HISTORICAL_DIR.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        field_id = data.get("field_id") if isinstance(data, dict) else None
        if not field_id:
            continue
        # Prefer the document that carries NOAA history.
        if field_id not in profiles or (data.get("noaa_history") and not profiles[field_id].get("noaa_history")):
            profiles[field_id] = data
    return profiles


def load_historical_profile(field_id: str) -> dict[str, Any] | None:
    profile = _profiles_by_field_id().get(field_id)
    if profile is None and str(field_id).startswith("osm-"):
        from rainout_agent import osm_venues

        profile = osm_venues.history_profile(field_id)
    return profile


def calibration_for(field_id: str, game_time: datetime | None) -> dict[str, Any] | None:
    """Return the month-specific calibration for a field, or None if unavailable."""
    profile = load_historical_profile(field_id)
    noaa = (profile or {}).get("noaa_history")
    if not noaa or not game_time:
        return None
    month = noaa.get("monthly", {}).get(f"{game_time.month:02d}") or {}
    if not month.get("days_observed") or "cancel_given_wet" not in month:
        return None
    station = noaa.get("station") or {}
    return {
        "month": f"{game_time.month:02d}",
        "cancel_given_wet": month["cancel_given_wet"],
        "wet_day_frac": month.get("wet_day_frac"),
        "rainout_day_frac": month.get("rainout_day_frac"),
        "rain_to_cancel_threshold_in": noaa.get("rain_to_cancel_threshold_in"),
        "station_id": station.get("id"),
        "station_name": station.get("name"),
        "station_distance_km": station.get("distance_km"),
        "period": noaa.get("period"),
        "source": noaa.get("source"),
    }


def rain_severity(cancel_given_wet: float, thunderstorm_likely: bool) -> float:
    """Share of the forecast rain chance that turns into rainout risk.

    Blends the field's historical heavy-rain share with ``SEVERITY_FLOOR``;
    thunderstorms always count fully because lightning rules stop play
    regardless of rain totals.
    """
    if thunderstorm_likely:
        return 1.0
    ratio = max(0.0, min(1.0, float(cancel_given_wet)))
    return round(SEVERITY_FLOOR + (1 - SEVERITY_FLOOR) * ratio, 3)
